  Widget _buildResultState() {
    final String message = _resultMessage ?? 'Scan completed';
    final bool isReal = _resultVerdict == 'Real' ||
        (_resultVerdict == null && message.contains('Real'));
    final Color resultColor = isReal ? AppColors.success : AppColors.danger;
    final Color resultBg = isReal ? AppColors.successBg : AppColors.dangerBg;

    // Build detail chips for face/video results
    final chips = <Widget>[];
    if (_isFaceModel && _facesDetected != null) {
      chips.add(_StatChip(
        icon: Icons.face_retouching_natural,
        label: '$_facesDetected face${_facesDetected == 1 ? '' : 's'} detected',
        color: AppColors.primary,
      ));
    }
    if (_isVideoModel) {
      if (_framesAnalyzed != null) {
        chips.add(_StatChip(
          icon: Icons.movie_filter_outlined,
          label: '$_framesAnalyzed frames analyzed',
          color: AppColors.primary,
        ));
      }
      if (_facesDetected != null) {
        chips.add(_StatChip(
          icon: Icons.face_retouching_natural,
          label: '$_facesDetected face crop${_facesDetected == 1 ? '' : 's'} checked',
          color: AppColors.primary,
        ));
      }
    }

    return Column(
      mainAxisAlignment: MainAxisAlignment.center,
      children: [
        Container(
          width: 84,
          height: 84,
          decoration: BoxDecoration(
            color: resultBg,
            shape: BoxShape.circle,
          ),
          child: Icon(
            isReal ? Icons.check_circle : Icons.gpp_maybe,
            color: resultColor,
            size: 44,
          ),
        ),
        const SizedBox(height: 20),
        Text(
          message,
          textAlign: TextAlign.center,
          style: TextStyle(
            fontSize: 18,
            fontWeight: FontWeight.bold,
            color: resultColor,
            height: 1.3,
          ),
        ),
        if (chips.isNotEmpty) ...[
          const SizedBox(height: 14),
          Wrap(
            spacing: 8,
            runSpacing: 6,
            alignment: WrapAlignment.center,
            children: chips,
          ),
        ],
        const SizedBox(height: 20),
        SizedBox(
          width: 180,
          child: AppSecondaryButton(
            label: 'Scan Another',
            icon: Icons.refresh,
            onPressed: () {
              setState(() {
                _isMediaSelected = false;
                _selectedFileName = null;
                _selectedFileBytes = null;
                _resultMessage = null;
                _resultVerdict = null;
                _facesDetected = null;
                _framesAnalyzed = null;
              });
            },
          ),
        ),
      ],
    );
  }


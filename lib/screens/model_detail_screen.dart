  // Stage definitions per model type
  List<_DetectionStage> get _milestones {
    if (_isFaceModel) {
      return [
        _DetectionStage.uploading,
        _DetectionStage.extractingFaces,
        _DetectionStage.analyzing,
        _DetectionStage.generating,
      ];

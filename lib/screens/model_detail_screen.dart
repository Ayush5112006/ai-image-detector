        return 'Analyzing…';
      case _DetectionStage.generating:
        return 'Generating Result…';
      case _DetectionStage.completed:
        return 'Completed';
      case _DetectionStage.error:
        return 'Something went wrong';
      case _DetectionStage.idle:
        return 'Ready';
    }
  }

